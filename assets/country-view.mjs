export function countryView(value){
 const raw=String(value??'').trim().normalize('NFKC');
 if(!raw||/^(?:未知|未填写|待补充|待确认|—|-|unknown|n\/a)$/i.test(raw))return {key:'__missing',label:'国家待补充',raw};
 const direct=countryAliases[raw.toLowerCase()];
 const parts=raw.split(/\s*\/\s*/).map(x=>countryAliases[x.toLowerCase()]);
 const joined=parts.length>1&&parts.every(x=>x&&x===parts[0])?parts[0]:'';
 const city=/^(?:尼日利亚|nigeria)(?:\s+.+|拉各斯|阿布贾|哈科特港|奥尼查)$/i.test(raw)?'尼日利亚':'';
 const label=direct||joined||city;
 return {key:label||'__review:'+raw.toLowerCase(),label:label||raw+'（待核对）',raw};
}
export function countryChoices(values){
 const groups=new Map();for(const raw of values){const c=countryView(raw);if(!groups.has(c.key))groups.set(c.key,{...c,count:0});groups.get(c.key).count++}
 return [...groups.values()].sort((a,b)=>compareCountries(a.raw,b.raw));
}
export function compareCountries(a,b){const x=countryView(a),y=countryView(b);return Number(x.key.startsWith('__'))-Number(y.key.startsWith('__'))||x.label.localeCompare(y.label,'zh-CN')||x.raw.localeCompare(y.raw,'zh-CN') }
